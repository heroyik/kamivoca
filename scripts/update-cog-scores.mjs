function getHanjaReading(word) {
  return word.split('').map(char => KANJI_TO_HANJA[char] || '').join('');
}

const raw = readFileSync(vocabPath, 'utf8');
const vocabJson = JSON.parse(raw);
const vocab = vocabJson.data;

console.log(`\n📝 Updating cog_score for ${vocab.length} words...\n`);

vocab.forEach(entry => {
  let krCore = entry.meaning
    .split(/[,(]/)[0]
    .replace(/아기/g, '')
    .replace(/하다/g, '')
    .replace(/시키기/g, '')
    .trim()
    .replace(/\s/g, ''); 
  
  const hanjaReading = getHanjaReading(entry.word);
  const isMatch = hanjaReading && (krCore.includes(hanjaReading) || hanjaReading.includes(krCore));
  
  entry.cog_score = isMatch ? 1.0 : 0.0;
});

writeFileSync(vocabPath, JSON.stringify(vocabJson, null, 2));
console.log(`✅ Successfully updated ${vocabPath}`);
